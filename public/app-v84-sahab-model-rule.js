(()=>{
  // قاعدة سحاب: لا تعتبر كلمة "سحاب" موديلًا إلا إذا كانت مرتبطة صراحة بوصف بنطلون/جيوب/رياضة.
  // العناوين مثل "سحاب - المدينة الصناعية" تبقى منطقة فقط ولا تدخل في تصنيف الموديلات/المخزون.
  window.CORVEX_SAHAB_MODEL_RULE={
    isProduct(text=''){
      const s=String(text).replace(/\s+/g,' ').trim();
      return /(?:بنطلون\s*سحاب|جيوب\s*سحاب|سحاب\s*جيوب|رياض[هة]\s*سحاب|سحاب\s*رياض[هة])/i.test(s);
    },
    classify(text=''){
      const s=String(text).replace(/\s+/g,' ').trim();
      if(/(?:جيوب\s*سحاب|سحاب\s*جيوب)/i.test(s))return 'جيوب سحاب';
      if(/(?:رياض[هة]\s*سحاب|سحاب\s*رياض[هة]|بنطلون\s*سحاب)/i.test(s))return 'رياضة سحاب';
      return '';
    }
  };
})();